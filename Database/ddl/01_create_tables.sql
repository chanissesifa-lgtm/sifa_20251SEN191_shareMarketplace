-- 1. Parent Table: COMPANIES
CREATE TABLE companies (
    company_id       NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ticker_symbol    VARCHAR2(15)   NOT NULL,
    company_name     VARCHAR2(150)  NOT NULL,
    sector           VARCHAR2(80)   NOT NULL,
    sub_industry     VARCHAR2(100),
    headquarters     VARCHAR2(120),
    cik_code         VARCHAR2(20),
    listing_status   VARCHAR2(20)   DEFAULT 'ACTIVE' NOT NULL,
    created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE mkt_data;

-- 2. Parent Table: INVESTORS
CREATE TABLE investors (
    investor_id      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_name        VARCHAR2(120)  NOT NULL,
    email            VARCHAR2(150)  NOT NULL,
    phone_number     VARCHAR2(30),
    investor_type    VARCHAR2(30)   DEFAULT 'INDIVIDUAL' NOT NULL,
    kyc_status       VARCHAR2(20)   DEFAULT 'VERIFIED' NOT NULL,
    wallet_balance   NUMBER(15, 2)  DEFAULT 0.00 NOT NULL,
    registered_at    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE mkt_data;

-- 3. Child Table: SHARE_OFFERINGS (Depends on COMPANIES)
CREATE TABLE share_offerings (
    offering_id      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id       NUMBER         NOT NULL,
    offering_code    VARCHAR2(30)   NOT NULL,
    total_shares     NUMBER(15, 0)  NOT NULL,
    available_shares NUMBER(15, 0)  NOT NULL,
    price_per_share  NUMBER(12, 2)  NOT NULL,
    offering_status  VARCHAR2(20)   DEFAULT 'OPEN' NOT NULL,
    opened_at        DATE           DEFAULT SYSDATE NOT NULL
) TABLESPACE mkt_data;

-- 4. Child Table: TRANSACTIONS (Depends on INVESTORS and SHARE_OFFERINGS)
CREATE TABLE transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    investor_id      NUMBER         NOT NULL,
    offering_id      NUMBER         NOT NULL,
    transaction_type VARCHAR2(10)   DEFAULT 'BUY' NOT NULL,
    shares_quantity  NUMBER(15, 0)  NOT NULL,
    execution_price  NUMBER(12, 2)  NOT NULL,
    total_amount     NUMBER(15, 2)  NOT NULL,
    tx_status        VARCHAR2(20)   DEFAULT 'COMPLETED' NOT NULL,
    executed_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE mkt_data;

-- 5. Child Table: COMPANY_PERFORMANCE (Depends on COMPANIES — holds fundamental metrics from fundamentals.csv)
CREATE TABLE company_performance (
    performance_id      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id          NUMBER         NOT NULL,
    period_ending       DATE           NOT NULL,
    fiscal_year         NUMBER(4, 0)   NOT NULL,
    total_revenue       NUMBER(18, 2),
    net_income          NUMBER(18, 2),
    total_assets        NUMBER(18, 2),
    total_liabilities   NUMBER(18, 2),
    earnings_per_share  NUMBER(10, 4),
    shares_outstanding  NUMBER(18, 0),
    recorded_at         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE mkt_data;

-- 6. Audit / Operational Table: AUDIT_LOG (Optional FK to INVESTORS with ON DELETE SET NULL)
CREATE TABLE audit_log (
    audit_id         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    investor_id      NUMBER,
    table_name       VARCHAR2(50)   NOT NULL,
    action_type      VARCHAR2(20)   NOT NULL,
    record_key       VARCHAR2(50),
    action_details   VARCHAR2(500),
    logged_at        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE mkt_data;