-- 1. COMPANIES Table
CREATE TABLE companies (
    company_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_symbol   VARCHAR2(15) UNIQUE,
    company_name    VARCHAR2(100) NOT NULL UNIQUE,
    sector          VARCHAR2(50) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELISTED')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. INVESTORS Table
CREATE TABLE investors (
    investor_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR2(100) NOT NULL,
    email           VARCHAR2(120) NOT NULL UNIQUE,
    wallet_balance  NUMBER(12, 2) DEFAULT 0 CHECK (wallet_balance >= 0),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. SHARE_OFFERINGS Table
CREATE TABLE share_offerings (
    offering_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id       NUMBER NOT NULL,
    price_per_share  NUMBER(10, 2) NOT NULL CHECK (price_per_share > 0),
    available_shares NUMBER(15) NOT NULL CHECK (available_shares >= 0),
    total_shares     NUMBER(15) NOT NULL CHECK (total_shares > 0),
    CONSTRAINT chk_offering_shares CHECK (available_shares <= total_shares),
    CONSTRAINT fk_offering_company FOREIGN KEY (company_id) REFERENCES companies(company_id)
);

-- 4. TRANSACTIONS Table
CREATE TABLE transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investor_id      NUMBER NOT NULL,
    offering_id      NUMBER NOT NULL,
    shares_bought    NUMBER(10) NOT NULL CHECK (shares_bought > 0),
    total_amount     NUMBER(12, 2) NOT NULL CHECK (total_amount > 0),
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_trans_investor FOREIGN KEY (investor_id) REFERENCES investors(investor_id),
    CONSTRAINT fk_trans_offering FOREIGN KEY (offering_id) REFERENCES share_offerings(offering_id)
);

-- 5. COMPANY_PERFORMANCE Table
CREATE TABLE company_performance (
    perf_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         NUMBER NOT NULL,
    period_ending      DATE,
    quarter_label      VARCHAR2(10) NOT NULL, -- e.g., '2015-Q4' or '2026-Q3'
    revenue            NUMBER(18, 2) NOT NULL,
    net_income         NUMBER(18, 2),
    earnings_per_share NUMBER(10, 2),
    cash_ratio         NUMBER(8, 2),
    profit_margin      NUMBER(6, 2) NOT NULL,
    trend_status       VARCHAR2(15) CHECK (trend_status IN ('RISING', 'STABLE', 'FALLING')),
    recorded_at        DATE DEFAULT SYSDATE,
    CONSTRAINT fk_perf_company FOREIGN KEY (company_id) REFERENCES companies(company_id)
);

-- 6. AUDIT_LOG Table
CREATE TABLE audit_log (
    log_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name       VARCHAR2(50) NOT NULL,
    action_type      VARCHAR2(30) NOT NULL,
    performed_by     VARCHAR2(50) DEFAULT USER,
    details          VARCHAR2(255),
    log_timestamp    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);